#!/usr/bin/env python3
"""
Evaluate a batch of randomized Twin4Build validation buildings.

The evaluator is intentionally separate from the FDD pipeline. It merges the
injected ground truth only AFTER diagnosis and produces paper-ready diagnostic
CSVs for:
- pooled binary fault detection,
- per-building metrics,
- strict fault-family classification,
- performance by injected mechanism and severity,
- room-level results,
- pre-onset false alarms,
- post-onset detection persistence,
- first-detection delay,
- first correct-family detection delay,
- fault-family confusion counts.

The script also verifies that the operational input file does not contain
forbidden injected-fault or controller-command fields.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd


NORMAL_DIAGNOSIS = "normal_or_no_rule_triggered"

FORBIDDEN_OPERATIONAL_COLUMNS = {
    "fault_type",
    "fault_severity",
    "fault_start",
    "fault_start_step",
    "restriction_factor",
    "fixed_valve_position",
    "fixed_valve_regime",
    "fixed_valve_quantile",
    "valve_upper_limit",
    "valve_lower_limit",
    "valve_limit_quantile",
    "valve_binding_fraction",
    "valve_mean_absolute_position_change",
    "valve_binding_count",
    "valve_post_fault_step_count",
    "valve_fault_activated",
    "controller_signal",
    "valve_max_flow",
    "healthy_valve_max_flow_kg_s",
}

DIAGNOSIS_TO_EVAL_FAMILY = {
    "possible_valve_leakage_or_stuck_open": "valve_fault",
    "possible_partially_closed_or_stuck_low_valve": "valve_fault",
    "hydraulic_restriction_with_comfort_impact": "restricted_or_hydraulic",
    "hydraulic_restriction_degraded": "restricted_or_hydraulic",
    "possible_compensated_hydraulic_restriction": "restricted_or_hydraulic",
    "possible_flow_or_control_instability": "restricted_or_hydraulic",
    "insufficient_heat_output": "insufficient_heat_output",
    "possible_emitter_undersizing_or_high_load": "insufficient_heat_output",
    "possible_excessive_heating_capacity_or_oversupply": "oversupply_or_overheating",
    "possible_oversupply_or_overheating": "oversupply_or_overheating",
    "possible_nonhydronic_or_unexplained_overheating": "oversupply_or_overheating",
    "comfort_violation_without_matched_diagnostic_rule": "unclassified",
}

PREDICTED_ROOM_FAMILY_TO_EVAL_FAMILY = {
    "normal": "normal",
    "restricted_or_hydraulic": "restricted_or_hydraulic",
    "stuck_open_or_leakage": "valve_fault",
    "stuck_low_valve": "valve_fault",
    "insufficient_heat_output": "insufficient_heat_output",
    "oversupply_or_overheating": "oversupply_or_overheating",
    "comfort_violation_unclassified": "unclassified",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--batch-manifest",
        required=True,
        help="CSV generated by scripts/23_run_t4b_random_building_batch.py.",
    )
    parser.add_argument(
        "--out-dir",
        default=None,
        help="Output directory. Defaults to the batch-manifest directory.",
    )
    return parser.parse_args()


def safe_div(num: float, den: float) -> float:
    return float(num / den) if den else np.nan


def binary_metrics(y_true: pd.Series, y_pred: pd.Series) -> dict[str, float]:
    y_true = y_true.astype(bool)
    y_pred = y_pred.astype(bool)

    tp = int((y_true & y_pred).sum())
    tn = int((~y_true & ~y_pred).sum())
    fp = int((~y_true & y_pred).sum())
    fn = int((y_true & ~y_pred).sum())

    precision = safe_div(tp, tp + fp)
    recall = safe_div(tp, tp + fn)
    specificity = safe_div(tn, tn + fp)
    accuracy = safe_div(tp + tn, tp + tn + fp + fn)

    if (
        not np.isnan(precision)
        and not np.isnan(recall)
        and precision + recall > 0
    ):
        f1 = 2 * precision * recall / (precision + recall)
    else:
        f1 = np.nan

    return {
        "TP": tp,
        "TN": tn,
        "FP": fp,
        "FN": fn,
        "precision": precision,
        "recall": recall,
        "specificity": specificity,
        "F1": f1,
        "accuracy": accuracy,
    }


def true_eval_family(fault_type: str) -> str:
    ft = str(fault_type).strip().lower()
    if ft == "healthy":
        return "normal"
    if ft == "restricted_flow":
        return "restricted_or_hydraulic"
    if ft in {"fixed_valve", "limited_opening", "limited_closing"}:
        return "valve_fault"
    return ft


def predicted_eval_family(family: str) -> str:
    return PREDICTED_ROOM_FAMILY_TO_EVAL_FAMILY.get(
        str(family).strip(),
        str(family).strip(),
    )


def split_diagnoses(value) -> list[str]:
    if value is None or pd.isna(value):
        return []
    text = str(value).strip()
    if not text or text == NORMAL_DIAGNOSIS:
        return []
    result = []
    for semi in text.split(";"):
        for comma in semi.split(","):
            item = comma.strip().strip("'").strip('"')
            if item and item != NORMAL_DIAGNOSIS:
                result.append(item)
    return result


def window_eval_families(value) -> set[str]:
    diagnoses = split_diagnoses(value)
    if not diagnoses:
        return {"normal"}
    return {
        DIAGNOSIS_TO_EVAL_FAMILY.get(d, "unclassified")
        for d in diagnoses
    }


def verify_blind_operational_file(path: Path) -> None:
    header = pd.read_csv(path, nrows=0)
    leaked = sorted(FORBIDDEN_OPERATIONAL_COLUMNS.intersection(header.columns))
    if leaked:
        raise ValueError(
            f"Blind-validation violation in {path}: forbidden columns {leaked}"
        )


def read_case(case_row: pd.Series) -> tuple[pd.DataFrame, pd.DataFrame]:
    case_id = str(case_row["case_id"])
    operational_path = Path(case_row["operational_path"])
    truth_path = Path(case_row["ground_truth_path"])
    room_summary_path = Path(case_row["room_summary_path"])
    diagnosed_path = Path(case_row["diagnosed_path"])
    building_manifest_path = Path(case_row["building_manifest_path"])

    for path in [
        operational_path,
        truth_path,
        room_summary_path,
        diagnosed_path,
        building_manifest_path,
    ]:
        if not path.exists():
            raise FileNotFoundError(f"Missing required case file: {path}")

    verify_blind_operational_file(operational_path)

    truth = pd.read_csv(truth_path)
    summary = pd.read_csv(room_summary_path)
    building = pd.read_csv(building_manifest_path)
    diagnosed = pd.read_csv(diagnosed_path)

    # Remove any legacy validation metadata from the diagnostic summary before
    # joining the separately stored ground truth.
    legacy_truth_cols = [
        c
        for c in [
            "fault_type",
            "fault_severity",
            "fault_start",
            "fault_start_step",
            "restriction_factor",
            "fixed_valve_position",
            "fixed_valve_regime",
            "fixed_valve_quantile",
            "valve_upper_limit",
            "valve_lower_limit",
            "valve_limit_quantile",
            "valve_binding_fraction",
            "valve_mean_absolute_position_change",
            "valve_binding_count",
            "valve_post_fault_step_count",
            "valve_fault_activated",
        ]
        if c in summary.columns
    ]
    summary = summary.drop(columns=legacy_truth_cols, errors="ignore")

    if summary["zone"].duplicated().any() or truth["zone"].duplicated().any():
        raise ValueError(f"Duplicate room zones in case {case_id}.")
    if set(summary["zone"]) != set(truth["zone"]):
        raise ValueError(
            f"Diagnosed/ground-truth zone sets differ for {case_id}: "
            f"missing={set(truth['zone']) - set(summary['zone'])}, "
            f"extra={set(summary['zone']) - set(truth['zone'])}"
        )

    room = summary.merge(
        truth,
        on=["zone"],
        how="left",
        validate="one_to_one",
        suffixes=("", "_truth"),
    )

    # Keep selected design variables useful for stratified analysis.
    design_cols = [
        c
        for c in [
            "zone",
            "zone_area_m2",
            "n_exterior_walls",
            "has_floor",
            "has_roof",
            "H_total_W_per_K",
            "design_heat_load_W",
            "emitter_nominal_power_W",
            "valve_authority",
        ]
        if c in building.columns
    ]
    design = building[design_cols].drop_duplicates("zone")

    duplicate_design_cols = [
        c for c in design.columns if c != "zone" and c in room.columns
    ]
    room = room.drop(columns=duplicate_design_cols, errors="ignore")
    room = room.merge(design, on="zone", how="left", validate="one_to_one")

    room["case_id"] = case_id
    room["true_fault"] = room["fault_type"].ne("healthy")
    room["predicted_fault"] = room["dominant_fault_family"].ne("normal")
    room["true_eval_family"] = room["fault_type"].map(true_eval_family)
    room["predicted_eval_family"] = room["dominant_fault_family"].map(
        predicted_eval_family
    )
    room["family_correct"] = (
        room["true_eval_family"] == room["predicted_eval_family"]
    )

    temporal_rows: list[dict] = []
    diagnosed["window_start"] = pd.to_datetime(
        diagnosed["window_start"],
        utc=True,
        errors="raise",
    )
    # Script 11's aggregation uses non-overlapping, 3-hour diagnostic windows.
    # A window's diagnosis is not available until all samples have arrived.
    # Half-open interval: [window_start, window_end); detection at window_end.
    diagnostic_duration = pd.Timedelta(hours=3)
    diagnosed["window_end"] = diagnosed["window_start"] + diagnostic_duration

    truth_by_zone = truth.set_index("zone").to_dict("index")

    for zone, g in diagnosed.groupby("zone", dropna=False):
        zone = str(zone)
        gt = truth_by_zone.get(zone)
        if gt is None:
            continue

        g = g.sort_values("window_start").copy()
        g["is_abnormal"] = g["diagnosis_text"].fillna(NORMAL_DIAGNOSIS).ne(
            NORMAL_DIAGNOSIS
        )
        true_family = true_eval_family(gt["fault_type"])
        g["is_correct_family"] = g["diagnosis_text"].map(
            lambda x: true_family in window_eval_families(x)
        )

        row = {
            "case_id": case_id,
            "zone": zone,
            "fault_type": gt["fault_type"],
            "fault_severity": gt.get("fault_severity", "none"),
            "true_eval_family": true_family,
            "n_windows": len(g),
            "all_window_abnormal_fraction": float(g["is_abnormal"].mean()),
        }

        if gt["fault_type"] == "healthy" or pd.isna(gt.get("fault_start")):
            row.update(
                {
                    "fault_start": pd.NaT,
                    "n_pre_windows": len(g),
                    "n_post_windows": 0,
                    "pre_onset_abnormal_fraction": float(g["is_abnormal"].mean()),
                    "post_onset_abnormal_fraction": np.nan,
                    "post_onset_correct_family_fraction": np.nan,
                    "first_detection_delay_h": np.nan,
                    "first_correct_family_delay_h": np.nan,
                }
            )
        else:
            fault_start = pd.to_datetime(gt["fault_start"], utc=True)
            # A window overlapping onset is neither a wholly healthy baseline
            # nor a wholly post-fault window. Exclude it from both comparisons.
            pre = g[g["window_end"] <= fault_start]
            post = g[g["window_start"] >= fault_start]

            first_abnormal = post.loc[post["is_abnormal"], "window_end"]
            first_correct = post.loc[post["is_correct_family"], "window_end"]

            first_detection_delay_h = (
                (first_abnormal.iloc[0] - fault_start).total_seconds() / 3600.0
                if len(first_abnormal)
                else np.nan
            )
            first_correct_family_delay_h = (
                (first_correct.iloc[0] - fault_start).total_seconds() / 3600.0
                if len(first_correct)
                else np.nan
            )

            row.update(
                {
                    "fault_start": fault_start,
                    "n_pre_windows": len(pre),
                    "n_post_windows": len(post),
                    "pre_onset_abnormal_fraction": (
                        float(pre["is_abnormal"].mean()) if len(pre) else np.nan
                    ),
                    "post_onset_abnormal_fraction": (
                        float(post["is_abnormal"].mean()) if len(post) else np.nan
                    ),
                    "post_onset_correct_family_fraction": (
                        float(post["is_correct_family"].mean())
                        if len(post)
                        else np.nan
                    ),
                    "first_detection_delay_h": first_detection_delay_h,
                    "first_correct_family_delay_h": first_correct_family_delay_h,
                }
            )

        temporal_rows.append(row)

    temporal = pd.DataFrame(temporal_rows)
    return room, temporal


def make_per_building_metrics(room_results: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for case_id, g in room_results.groupby("case_id", dropna=False):
        metrics = binary_metrics(g["true_fault"], g["predicted_fault"])
        faulty = g[g["true_fault"]]
        metrics.update(
            {
                "case_id": case_id,
                "seed": (
                    int(g["seed"].dropna().iloc[0])
                    if "seed" in g.columns and g["seed"].notna().any()
                    else np.nan
                ),
                "n_rooms": len(g),
                "n_faulty": int(g["true_fault"].sum()),
                "n_healthy": int((~g["true_fault"]).sum()),
                "family_accuracy_all_rooms": float(g["family_correct"].mean()),
                "faulty_family_accuracy": (
                    float(faulty["family_correct"].mean())
                    if len(faulty)
                    else np.nan
                ),
            }
        )
        rows.append(metrics)
    return pd.DataFrame(rows)


def make_group_performance(
    room_results: pd.DataFrame,
    group_cols: list[str],
) -> pd.DataFrame:
    rows = []
    faulty = room_results[room_results["true_fault"]].copy()

    for keys, g in faulty.groupby(group_cols, dropna=False):
        if not isinstance(keys, tuple):
            keys = (keys,)
        row = dict(zip(group_cols, keys))
        row.update(
            {
                "n_rooms": len(g),
                "detected_rooms": int(g["predicted_fault"].sum()),
                "detection_rate": float(g["predicted_fault"].mean()),
                "correct_family_rooms": int(g["family_correct"].sum()),
                "family_accuracy": float(g["family_correct"].mean()),
                "mean_main_diagnosis_fraction": float(
                    g["main_diagnosis_fraction"].mean()
                ),
                "mean_comfort_violation_fraction": float(
                    g["comfort_violation_fraction"].mean()
                ),
            }
        )
        rows.append(row)

    return pd.DataFrame(rows)


def pooled_window_fraction(
    temporal: pd.DataFrame,
    numerator_fraction_col: str,
    count_col: str,
    mask: pd.Series,
) -> float:
    g = temporal.loc[mask].copy()
    if g.empty:
        return np.nan
    valid = g[numerator_fraction_col].notna() & g[count_col].gt(0)
    g = g.loc[valid]
    if g.empty:
        return np.nan
    numerator = (
        g[numerator_fraction_col].astype(float) * g[count_col].astype(float)
    ).sum()
    denominator = g[count_col].sum()
    return safe_div(numerator, denominator)


def write_text_summary(
    path: Path,
    aggregate: pd.DataFrame,
    per_building: pd.DataFrame,
    room_results: pd.DataFrame,
    temporal: pd.DataFrame,
) -> None:
    a = aggregate.iloc[0]

    lines = [
        "Randomized multi-building validation summary",
        "=" * 47,
        f"Buildings: {int(a['n_buildings'])}",
        f"Rooms: {int(a['n_rooms'])}",
        f"Faulty rooms: {int(a['n_faulty'])}",
        f"Healthy rooms: {int(a['n_healthy'])}",
        "",
        "Pooled room-level fault detection",
        f"TP={int(a['TP'])}, TN={int(a['TN'])}, FP={int(a['FP'])}, FN={int(a['FN'])}",
        f"Precision={a['precision']:.4f}",
        f"Recall={a['recall']:.4f}",
        f"Specificity={a['specificity']:.4f}",
        f"F1={a['F1']:.4f}",
        f"Accuracy={a['accuracy']:.4f}",
        f"Fault-family accuracy (faulty rooms)={a['faulty_family_accuracy']:.4f}",
        "",
        "Temporal behaviour",
        f"Healthy-window false-alarm fraction={a['healthy_window_false_alarm_fraction']:.4f}",
        f"Fault-room pre-onset abnormal fraction={a['fault_room_pre_onset_abnormal_fraction']:.4f}",
        f"Fault-room post-onset abnormal fraction={a['fault_room_post_onset_abnormal_fraction']:.4f}",
        f"Fault-room post-onset correct-family fraction={a['fault_room_post_onset_correct_family_fraction']:.4f}",
        f"Median first-detection delay [h]={a['median_first_detection_delay_h']:.3f}",
        f"Median first correct-family delay [h]={a['median_first_correct_family_delay_h']:.3f}",
        "",
        "Per-building distribution",
        f"Mean accuracy={per_building['accuracy'].mean():.4f}",
        f"Std accuracy={per_building['accuracy'].std(ddof=1):.4f}" if len(per_building) > 1 else "Std accuracy=NA (one building)",
        f"Mean F1={per_building['F1'].mean():.4f}",
        f"Std F1={per_building['F1'].std(ddof=1):.4f}" if len(per_building) > 1 else "Std F1=NA (one building)",
        "",
        "Fault mechanisms",
    ]

    mechanism_counts = room_results["fault_type"].value_counts().sort_index()
    for mechanism, count in mechanism_counts.items():
        lines.append(f"  {mechanism}: {count}")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    args = parse_args()
    batch_manifest_path = Path(args.batch_manifest)
    out_dir = Path(args.out_dir) if args.out_dir else batch_manifest_path.parent
    out_dir.mkdir(parents=True, exist_ok=True)

    batch = pd.read_csv(batch_manifest_path)
    if "status" in batch.columns:
        batch = batch[batch["status"].isin(["ok", "reused"])].copy()

    if batch.empty:
        raise ValueError("No successfully completed cases in the batch manifest.")

    room_parts = []
    temporal_parts = []

    for _, case_row in batch.iterrows():
        case_id = case_row["case_id"]
        print(f"Evaluating {case_id} ...")
        room, temporal = read_case(case_row)
        room_parts.append(room)
        temporal_parts.append(temporal)

    room_results = pd.concat(room_parts, ignore_index=True)
    temporal = pd.concat(temporal_parts, ignore_index=True)

    pooled = binary_metrics(
        room_results["true_fault"],
        room_results["predicted_fault"],
    )
    faulty_rooms = room_results[room_results["true_fault"]]

    per_building = make_per_building_metrics(room_results)

    healthy_temporal = temporal["fault_type"].eq("healthy")
    faulty_temporal = ~healthy_temporal

    healthy_false_alarm_fraction = pooled_window_fraction(
        temporal,
        "pre_onset_abnormal_fraction",
        "n_pre_windows",
        healthy_temporal,
    )
    fault_pre_abnormal_fraction = pooled_window_fraction(
        temporal,
        "pre_onset_abnormal_fraction",
        "n_pre_windows",
        faulty_temporal,
    )
    fault_post_abnormal_fraction = pooled_window_fraction(
        temporal,
        "post_onset_abnormal_fraction",
        "n_post_windows",
        faulty_temporal,
    )
    fault_post_correct_family_fraction = pooled_window_fraction(
        temporal,
        "post_onset_correct_family_fraction",
        "n_post_windows",
        faulty_temporal,
    )

    aggregate_row = {
        "n_buildings": room_results["case_id"].nunique(),
        "n_rooms": len(room_results),
        "n_faulty": int(room_results["true_fault"].sum()),
        "n_healthy": int((~room_results["true_fault"]).sum()),
        **pooled,
        "family_accuracy_all_rooms": float(room_results["family_correct"].mean()),
        "faulty_family_accuracy": (
            float(faulty_rooms["family_correct"].mean())
            if len(faulty_rooms)
            else np.nan
        ),
        "healthy_window_false_alarm_fraction": healthy_false_alarm_fraction,
        "fault_room_pre_onset_abnormal_fraction": fault_pre_abnormal_fraction,
        "fault_room_post_onset_abnormal_fraction": fault_post_abnormal_fraction,
        "fault_room_post_onset_correct_family_fraction": fault_post_correct_family_fraction,
        "median_first_detection_delay_h": float(
            temporal.loc[faulty_temporal, "first_detection_delay_h"].median()
        ),
        "median_first_correct_family_delay_h": float(
            temporal.loc[faulty_temporal, "first_correct_family_delay_h"].median()
        ),
    }
    aggregate = pd.DataFrame([aggregate_row])

    mechanism_performance = make_group_performance(
        room_results,
        ["fault_type"],
    )
    severity_performance = make_group_performance(
        room_results,
        ["fault_type", "fault_severity"],
    )

    family_confusion = pd.crosstab(
        room_results["true_eval_family"],
        room_results["predicted_eval_family"],
        rownames=["true_family"],
        colnames=["predicted_family"],
        margins=True,
    )

    restriction_results = room_results[
        room_results["fault_type"].eq("restricted_flow")
    ][
        [
            c
            for c in [
                "case_id",
                "zone",
                "fault_severity",
                "restriction_factor",
                "predicted_fault",
                "family_correct",
                "dominant_fault_family",
                "main_diagnosis",
                "main_diagnosis_fraction",
                "comfort_violation_fraction",
                "valve_position_mean",
                "m_dot_density_mean",
                "Q_density_mean",
                "deltaT_water_mean",
            ]
            if c in room_results.columns
        ]
    ].copy()

    valve_fault_activation_results = room_results[
        room_results["fault_type"].isin(
            ["fixed_valve", "limited_opening", "limited_closing"]
        )
    ][
        [
            c
            for c in [
                "case_id",
                "zone",
                "fault_type",
                "fault_severity",
                "fixed_valve_position",
                "fixed_valve_quantile",
                "valve_limit_quantile",
                "valve_upper_limit",
                "valve_lower_limit",
                "valve_binding_fraction",
            "valve_mean_absolute_position_change",
                "valve_binding_count",
                "valve_post_fault_step_count",
                "valve_fault_activated",
                "predicted_fault",
                "family_correct",
                "dominant_fault_family",
                "main_diagnosis",
                "main_diagnosis_fraction",
                "comfort_violation_fraction",
                "valve_position_mean",
            ]
            if c in room_results.columns
        ]
    ].copy()

    # Evaluation-only activation strata. This never changes the primary injected
    # ground-truth label or the main confusion matrix. Controller requests are
    # deliberately not available to diagnostic code.
    if "valve_binding_fraction" in valve_fault_activation_results.columns:
        val = pd.to_numeric(
            valve_fault_activation_results["valve_binding_fraction"],
            errors="coerce",
        )
        valve_fault_activation_results["activation_stratum"] = np.select(
            [val.isna(), val < 0.01, val < 0.05],
            ["unknown", "<1%", "1-5%"],
            default=">=5%",
        )

    # Report the ability to detect valve faults at different physical activation
    # levels without excluding low-activation faults from primary metrics.
    activation_metrics_rows = []
    if "activation_stratum" in valve_fault_activation_results.columns:
        for activation, group in valve_fault_activation_results.groupby(
            "activation_stratum", dropna=False
        ):
            activation_metrics_rows.append({
                "activation_stratum": activation,
                "n_injected_valve_faults": len(group),
                "detected_fraction": float(group["predicted_fault"].mean()),
                "correct_family_fraction": float(group["family_correct"].mean()),
            })
    activation_metrics = pd.DataFrame(activation_metrics_rows)

    # Merge temporal fields into the per-room table for a single comprehensive
    # analysis dataset.
    temporal_merge_cols = [
        "case_id",
        "zone",
        "pre_onset_abnormal_fraction",
        "post_onset_abnormal_fraction",
        "post_onset_correct_family_fraction",
        "first_detection_delay_h",
        "first_correct_family_delay_h",
    ]
    room_results = room_results.merge(
        temporal[temporal_merge_cols],
        on=["case_id", "zone"],
        how="left",
        validate="one_to_one",
    )

    outputs = {
        "aggregate_metrics.csv": aggregate,
        "per_building_metrics.csv": per_building,
        "per_room_results.csv": room_results,
        "fault_mechanism_performance.csv": mechanism_performance,
        "fault_severity_performance.csv": severity_performance,
        "temporal_detection_metrics.csv": temporal,
        "restriction_factor_results.csv": restriction_results,
        "valve_fault_activation_results.csv": valve_fault_activation_results,
        "valve_fault_activation_stratified_metrics.csv": activation_metrics,
    }

    for filename, df in outputs.items():
        df.to_csv(out_dir / filename, index=False)

    family_confusion.to_csv(out_dir / "fault_family_confusion.csv")

    write_text_summary(
        out_dir / "paper_validation_summary.txt",
        aggregate=aggregate,
        per_building=per_building,
        room_results=room_results,
        temporal=temporal,
    )

    print("\n" + "=" * 100)
    print("POOLED RANDOMIZED-VALIDATION METRICS")
    print("=" * 100)
    print(aggregate.round(4).to_string(index=False))

    print("\n" + "=" * 100)
    print("PER-FAULT-MECHANISM PERFORMANCE")
    print("=" * 100)
    if mechanism_performance.empty:
        print("No faulty rooms.")
    else:
        print(mechanism_performance.round(4).to_string(index=False))

    print("\n" + "=" * 100)
    print("FAULT-FAMILY CONFUSION")
    print("=" * 100)
    print(family_confusion.to_string())

    print("\nSaved paper-validation diagnostics to:")
    print(out_dir)
    for filename in list(outputs) + [
        "fault_family_confusion.csv",
        "paper_validation_summary.txt",
    ]:
        print(f"  - {filename}")


